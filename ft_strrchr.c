char	*ft_strrchr(const char *s, int c)
{
	int	i;

	i = 0;
	while (!s)
	{
		if (*s++ == (char) c)
		{
			return ((char *)s);
		}
	}
	if (*s == (char) c)
	{
		return ((char *)s);
	}
	return (0);
}
